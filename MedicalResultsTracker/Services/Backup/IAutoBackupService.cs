namespace MedicalResultsTracker.Services.Backup
{
    /// <summary>
    /// Автоматическая копия в папку, выбранную пользователем.
    ///
    /// Сети здесь нет и не будет: приложение только пишет файл в папку, на которую человек
    /// сам выдал разрешение. Синхронизируется ли эта папка с облаком — дело того приложения,
    /// которое её синхронизирует, а не наше. Поэтому обещание «данные не передаются» остаётся
    /// правдой, а в Play не появляется ни сетевых разрешений, ни передачи данных о здоровье.
    /// </summary>
    public interface IAutoBackupService
    {
        /// <summary>Папка выбрана и разрешение на неё ещё действует.</summary>
        bool IsConfigured { get; }

        /// <summary>Человекочитаемое имя папки — то, что показывать в настройках.</summary>
        string? FolderName { get; }

        /// <summary>Когда автоматическая копия удалась в последний раз.</summary>
        DateTime? LastBackupUtc { get; }

        /// <summary>Открывает системный выбор папки. false — пользователь отказался.</summary>
        Task<bool> ChooseFolderAsync();

        /// <summary>Забывает папку и снимает разрешение на неё.</summary>
        void Forget();

        /// <summary>
        /// Пишет копию, если данные изменились с прошлого раза. Ничего не изменилось —
        /// ничего и не делает: копия нужна не по календарю, а когда есть что копировать.
        /// Возвращает true, если файл был записан.
        /// </summary>
        Task<bool> BackupIfChangedAsync();

        /// <summary>Пишет копию независимо от изменений — по кнопке в настройках.</summary>
        Task<bool> BackupNowAsync();
    }
}
